import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import '../js/planner-model.js';
import '../js/team-store.js';

export function buildSeed(events, legacy) {
  const store = new globalThis.TeamStore({});
  store.validate(legacy);
  const rows = new Map();
  for (const event of events) {
    if (!event || !/^[a-zA-Z0-9_-]{1,100}$/.test(event.id) || rows.has(event.id) ||
        typeof event.title !== 'string' || typeof event.date !== 'string') throw new Error('Invalid or duplicate event metadata.');
    const metadata = { id: event.id, title: event.title, date: event.date,
      start: event.start || '', end: event.end || '', location: event.location || '' };
    rows.set(event.id, { event_id: event.id, event: metadata, seeded_event: true,
      names: legacy.assignments[event.id]?.names || [], updated_at: legacy.assignments[event.id]?.updated_at || null });
  }
  for (const [id, record] of Object.entries(legacy.assignments)) {
    if (!rows.has(id) && record.names.length) rows.set(id, { event_id: id,
      event: { ...record.event, id }, seeded_event: false, names: record.names, updated_at: record.updated_at || null });
  }
  // ASCII JSON keeps SQL portable while preserving every Unicode code unit.
  const payload = JSON.stringify([...rows.values()], null, 2).replace(/[\u007f-\uffff]/g,
    char => '\\u' + char.charCodeAt(0).toString(16).padStart(4, '0')).replaceAll("'", "''");
  return `-- Generated by node scripts/prepare-supabase.mjs. Do not edit by hand.
-- ${events.length} real events; ${rows.size - events.length} preserved legacy orphans.
-- Run after 001_team_store.sql. Reruns NEVER restore cleared/changed names.
begin;
set local standard_conforming_strings = on;
create temporary table team_seed on commit drop as
select event_id, event, seeded_event,
  public.normalize_team_names(names) as names, updated_at
from jsonb_to_recordset('${payload}'::jsonb)
  as seed(event_id text, event jsonb, seeded_event boolean, names jsonb, updated_at timestamptz);

insert into public.team_assignments (event_id, event, seeded_event, names, updated_at)
select event_id, event, seeded_event, names, updated_at from team_seed
on conflict (event_id) do nothing;

-- Only trusted setup SQL can update metadata. Retain removed events/orphans.
update public.team_assignments as target
set event = seed.event, seeded_event = true
from team_seed as seed
where target.event_id = seed.event_id and seed.seeded_event;
commit;
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === fs.realpathSync(process.argv[1])) {
  const root = new URL('../', import.meta.url);
  const { events } = JSON.parse(fs.readFileSync(new URL('data/events.json', root), 'utf8'));
  const legacy = JSON.parse(fs.readFileSync(new URL('data/team.json', root), 'utf8'));
  fs.writeFileSync(new URL('supabase/002_seed_team_schedule.sql', root), buildSeed(events, legacy));
  console.log(`Generated supabase/002_seed_team_schedule.sql with ${events.length} events; legacy names preserved on first insert only.`);
}
